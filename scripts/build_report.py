def table_s2():
    rows = {r["system"]: r for r in json.loads((RES / "exp_s2_final.json").read_text(encoding="utf-8"))}
    base = {r["system"]: r for r in json.loads((RES / "baselines_dev_sv.json").read_text(encoding="utf-8"))
            if r["task"] == "S2"}
    spec = [(r"All usages negative", base["all 0"]["macro_f1"], None),
            (r"Random (50/50)", base["random 50/50"]["macro_f1"], None),
            (r"$\cos(\mathbf{x}_i,\mathbf{g})$ (\emph{existing})", *_s2(rows, "existing: gloss cosine + threshold")),
            (r"Multilingual-E5 sentence cosine", *_s2(rows, "sentence Transformer (E5) cosine + threshold")),
            (r"APPNP propagation of $\cos(\mathbf{x}_i,\mathbf{g})$", *_s2(rows, "APPNP propagation on usage graph")),
            (r"\sys{} support probability", *_s2(rows, "SiamGNN support probability + LOWO threshold")),
            (r"One-shot prototype refinement (\emph{ours})", *_s2(rows, "few-shot prototype refinement")),
            (r"Few-shot logistic-regression calibrator", *_s2(rows, "few-shot calibrator (LogReg on label-free features)"))]
    bf = max(f for _, f, _ in spec)
    ba = max(a for _, _, a in spec if a is not None)
    out = [r"\begin{tabular}{@{}lcc@{}}", r"\toprule", r"System & macro-F1 & AUC \\", r"\midrule"]
    for i, (name, f, a) in enumerate(spec):
        if i == 2:
            out.append(r"\midrule")
        out.append(f"{name} & {cell(one(f), bf)} & {cell(one(a), ba) if a is not None else '--'} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    (TABLES / "s2_main.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


def _s2(rows, key):
    return rows[key]["macro_f1"], rows[key]["mean_auc"]


