# ----------------------------------------------------------------------------- helpers
def tex_escape(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


def f3(x):
    """.815 style (ACL tables), keeps the sign."""
    s = f"{x:.3f}"
    return s.replace("0.", ".", 1) if s.startswith(("0.", "-0.")) else s


def cell(v, best=None, k=False):
    """v = (mean, std, n) or None."""
    if v is None:
        return "--"
    m, s, n = v
    txt = f"{m:.1f}" if k else f3(m)
    if best is not None and not k and abs(m - best) < 5e-4:
        txt = r"\textbf{" + txt + "}"
    if n > 1 and not k:
        txt += r"\std{" + f3(s) + "}"
    return txt


def ms(rows, prefix, prot, key):
    v = [r[key] for r in rows if r["system"].startswith(prefix) and r["protocol"] == prot and key in r]
    return (float(np.mean(v)), float(np.std(v)), len(v)) if v else None


def one(x):
    return (float(x), 0.0, 1)


def grid_value(method, params):
    log = (RES / "exp_subtask1_log.txt").read_text(encoding="utf-8")
    m = re.search(rf"^{method}\s+{re.escape(params)}\s+B3=([\d.]+) rho=([-\d.]+) k=([\d.]+)", log, re.M)
    return one(m.group(1)), one(m.group(2)), one(m.group(3))


# ----------------------------------------------------------------------------- author block
def write_author():
    src = ROOT / "configs" / "author.json"
    if not src.exists():
        src = ROOT / "configs" / "author.example.json"
        print("configs/author.json not found: using the placeholders in configs/author.example.json")
    a = json.loads(src.read_text(encoding="utf-8"))
    lines = [f"% generated by scripts/build_report.py from configs/{src.name} -- edit that file, not this one"]
    for macro, key in [("teamname", "team"), ("authorname", "name"), ("programme", "programme"),
                       ("facultyen", "faculty_en"), ("university", "university"), ("city", "city"),
                       ("authoremail", "email")]:
        lines.append(rf"\newcommand{{\{macro}}}{{{{{tex_escape(a.get(key, ''))}}}}}")
    url = a.get("code_url", "").strip()  # empty -> no code footnote
    lines.append(r"\newcommand{\codefootnote}{" + (r"\footnote{Code: \url{" + url + "}.}" if url.startswith("http") else "") + "}")
    note = a.get("author_note", "").strip()  # optional footnote on the author name
    lines.append(r"\newcommand{\authornote}{" + (r"\thanks{\ " + tex_escape(note) + "}" if note else "") + "}")
    ack = a.get("acknowledgment_note", "").strip()  # optional sentence before the acknowledgments
    lines.append(r"\newcommand{\acknowledgmentnote}{" + (tex_escape(ack) + " " if ack else "") + "}")
    (REPORT / "author.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


# ----------------------------------------------------------------------------- Table 1: Subtask 1
def table_s1():
    rows = json.loads((RES / "exp_main.json").read_text(encoding="utf-8"))
    hyb = json.loads((RES / "exp_hybrid.json").read_text(encoding="utf-8"))
    sg_ag = next(h for h in hyb if h["similarity"] == "SiamGNN" and h["algorithm"] == "agglo-avg")
    ap = grid_value("ap", '{"preference": null, "min_size": 0}')
    dm = grid_value("dmon", '{"k_max": 8, "knn": 10, "collapse": 0.5, "min_size": 0}')
    K = ["synEN_b3", "synEN_rho", "synEN_k", "SV_b3", "SV_rho", "SV_k"]

    def from_main(prefix, prot):
        return {k: ms(rows, prefix, prot, k) for k in K}
    zero = [
        ("One cluster per word", from_main("1C1W", "-")),
        (r"\xll{} + Affinity Propagation", {"SV_b3": ap[0], "SV_rho": ap[1], "SV_k": ap[2]}),
        (r"\xll{} + DMoN (unsupervised GNN)", {"SV_b3": dm[0], "SV_rho": dm[1], "SV_k": dm[2]}),
        (r"\xll{} + agglomerative, $t{=}.40$ (\emph{existing})", from_main("XL-LEXEME + agglomerative (t=", "synEN-tune")),
        (r"\xll{} + correlation clustering, $\theta{=}.55$", from_main("XL-LEXEME + correlation clustering (t=", "synEN-tune")),
        (r"Siamese head, no GNN + CC", from_main("Siamese head + CC (theta", "synEN-train")),
        (r"\sys{} + CC", from_main("SiamGNN + CC (theta", "synEN-train")),
        (r"\sys{} (3-seed ensemble) + agglomerative",
         {"synEN_b3": one(sg_ag["synEN"][0]), "synEN_rho": one(sg_ag["synEN"][1]), "synEN_k": one(sg_ag["synEN"][2]),
          "SV_b3": one(sg_ag["SV"][0]), "SV_rho": one(sg_ag["SV"][1]), "SV_k": one(sg_ag["SV"][2])}),
    ]
    few = [
        (r"\xll{} + agglomerative", from_main("XL-LEXEME + agglomerative", "SV-LOWO")),
        (r"\xll{} + correlation clustering", from_main("XL-LEXEME + correlation clustering", "SV-LOWO")),
        (r"\sys{} + few-shot adaptation + CC", from_main("SiamGNN + few-shot", "SV-LOWO")),
    ]
    out = [r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
           r" & \multicolumn{3}{c}{Synthetic English (20 held-out words)} & \multicolumn{3}{c}{Swedish dev (10 words)} \\",
           r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
           r"System & 1a B$^3$-F1 & 1b $\rho$ & $k$ & 1a B$^3$-F1 & 1b $\rho$ & $k$ \\", r"\midrule",
           r"\multicolumn{7}{@{}l}{\emph{Zero-shot: thresholds and models fit on synthetic-English training words only}} \\"]
    for block, rs in [("zero", zero), ("few", few)]:
        if block == "few":
            out += [r"\midrule",
                    r"\multicolumn{7}{@{}l}{\emph{Few-shot Swedish: leave-one-word-out, the other nine words choose $t$ or adapt the model}} \\"]
        best = {k: max((v[k][0] for _, v in rs if v.get(k)), default=None) for k in K}
        for name, v in rs:
            out.append(name + " & " + " & ".join(cell(v.get(k), best[k], k=k.endswith("_k")) for k in K) + r" \\")
    out += [r"\midrule", r"Gold senses per word & & & 3.65 & & & 5.7 \\", r"\bottomrule", r"\end{tabular}"]
    (TABLES / "s1_main.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


