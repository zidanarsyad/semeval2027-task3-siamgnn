# ----------------------------------------------------------------------------- compile
def compile_pdf():
    def run(cmd):
        p = subprocess.run(cmd, cwd=REPORT, capture_output=True, text=True, encoding="utf-8", errors="replace")
        return p.returncode, p.stdout + p.stderr
    tex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "paper.tex"]
    rc, log = run(tex)
    if rc:
        sys.exit("pdflatex failed:\n" + log[-3000:])
    rc, blog = run(["bibtex", "paper"])
    if rc:
        print("bibtex warnings/errors:\n" + blog[-2000:])
    for _ in range(2):
        rc, log = run(tex)
        if rc:
            sys.exit("pdflatex failed:\n" + log[-3000:])
    full = (REPORT / "paper.log").read_text(encoding="utf-8", errors="replace")
    pages = re.search(r"Output written on paper\.pdf \((\d+) pages?", full)
    warn = [l for l in full.splitlines() if re.search(r"(Warning|Overfull|undefined)", l)
            and "Font shape" not in l]
    print(f"report/paper.pdf: {pages.group(1) if pages else '?'} pages")
    for l in warn:
        print("  ", l[:160])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-pdf", action="store_true")
    args = ap.parse_args()
    TABLES.mkdir(parents=True, exist_ok=True)
    write_author()
    table_s1()
    table_s2()
    table_s1_extra()
    table_per_word()
    print("author.tex and tables written")
    if not args.no_pdf:
        compile_pdf()


if __name__ == "__main__":
    main()
